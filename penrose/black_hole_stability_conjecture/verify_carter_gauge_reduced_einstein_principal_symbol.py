def validate_variables(data: dict[str, Any]) -> dict[str, tuple[str, ...]]:
    vars_section = data.get("variables")
    require(isinstance(vars_section, dict), "variables must be an object")
    phase = tuple(vars_section.get("phase_variables", []))
