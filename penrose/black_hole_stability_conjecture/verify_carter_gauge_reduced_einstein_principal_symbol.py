# Trapped-constraint generators (must match QIEDT/TCDEDT).
P_R = x**2 + ell**2 + q**2
P_dR = x * ell + q**2
P_xq = x * q + ell * q - q**2

# Gauge-tangent SOS square (must match QIEDT).
SOS_SQUARE = c * x - ell
SOS_WEIGHT = s
SOS_DEFECT = SOS_WEIGHT * SOS_SQUARE**2

# Kerr-clean backend density.
RHO_BACKEND = h * x**2 + tau * q**2

# GPDDT gravitational density q_grav (must match QIEDT/GPDDT).
Q_GRAV = (
    h * x**2
    - 2 * s * c * x * ell
    + s * c**2 * x**2
    + s * ell**2
    + tau * q**2
    + diag_slack * (x**2 + ell**2 + q**2)
    + bilinear_slack * (x * ell + x * q + ell * q)
)


# --------------------------------------------------------- expression parsing

def parse_expr(text: str) -> sp.Expr:
    """Parse a sympy expression string over the declared symbol set.

    Also rejects non-polynomial expressions (e.g. rational functions or
    transcendental functions of the declared variables) by attempting a
    sympy Poly conversion over the full symbol set.
    """
    require(isinstance(text, str) and text,
            "expression must be a nonempty string")
    try:
        expr = sp.sympify(text, locals=ALL_SYMBOLS)
    except (sp.SympifyError, TypeError, SyntaxError) as exc:
        raise ValueError(f"cannot parse expression {text!r}: {exc}") from exc
    # Reject non-polynomial inputs (e.g. 1/x, sin(x), etc.) by attempting
    # a Poly conversion.  This catches rational functions whose
    # denominators contain declared variables.
    try:
        sp.Poly(sp.expand(expr), x, ell, q, h, s, tau, c,
                diag_slack, bilinear_slack, rho_R, rho_dR, rho_xq)
    except sp.PolynomialError as exc:
        raise ValueError(f"expression {text!r} is not a polynomial "
                         f"in the declared variables: {exc}") from exc
    except Exception as exc:  # pragma: no cover - defensive
        # GeneratorsNeededError and other sympy polynomial errors are
        # subclasses of PolynomialError, but we catch broadly here for
        # forward-compatibility with future sympy versions.
        if "poly" in type(exc).__name__.lower() or "generator" in type(exc).__name__.lower():
            raise ValueError(f"expression {text!r} is not a polynomial "
                             f"in the declared variables: {exc}") from exc
        raise
    return expr


def free_symbols_in(expr: sp.Expr, allowed: tuple[str, ...]) -> set[str]:
    allowed_set = {ALL_SYMBOLS[name] for name in allowed}
    extras = expr.free_symbols - allowed_set
    return {str(sym) for sym in extras}


def require_in_vars(expr: sp.Expr, allowed: tuple[str, ...], ctx: str) -> None:
    extras = free_symbols_in(expr, allowed)
    require(not extras,
            f"{ctx}: expression contains undeclared symbols {sorted(extras)}")


def phase_degree(monoms: tuple[int, ...]) -> int:
    """Total degree in the phase variables (x, ell, q) = first three slots."""
    return sum(monoms[:3])


# --------------------------------------------------------- ideal membership

def reduce_mod_ideal(poly: sp.Expr, generators: list[sp.Expr]) -> sp.Expr:
    """Reduce a polynomial modulo an ideal using sympy's Groebner basis.

    Returns the canonical normal-form remainder.  If the remainder is
    zero, `poly` lies in the ideal generated by `generators`.
    """
    poly = sp.expand(poly)
    if poly == 0:
        return sp.Integer(0)
    # Collect all free symbols across the generators and the polynomial,
    # then order them deterministically (by name) for a reproducible
    # Groebner basis.
    symbols_set: set[sp.Symbol] = set()
    for g in generators:
        symbols_set |= g.free_symbols
    symbols_set |= poly.free_symbols
    if not symbols_set:
        return poly
    symbols_sorted = sorted(symbols_set, key=lambda sym: sym.name)
    try:
        gb = sp.groebner(list(generators), *symbols_sorted, order="grlex")
        rem = gb.reduce(poly)
    except Exception as exc:  # pragma: no cover - defensive
        raise ValueError(f"Groebner reduction failed: {exc}") from exc
    # sympy's GroebnerBasis.reduce returns a tuple (quotient_list, remainder).
    if isinstance(rem, tuple):
        return sp.expand(rem[1])
    return sp.expand(rem)


def is_in_ideal(poly: sp.Expr, generators: list[sp.Expr]) -> bool:
    return reduce_mod_ideal(poly, generators) == 0


def is_in_augmented_ideal(poly: sp.Expr) -> bool:
    """Membership in I_trap + <s*(c*x-ell)**2>."""
    return is_in_ideal(poly, [P_R, P_dR, P_xq, SOS_DEFECT])


