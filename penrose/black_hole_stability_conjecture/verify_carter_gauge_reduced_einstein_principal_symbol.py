#!/usr/bin/env python3
"""Verify the Gauge-Reduced Linearized Einstein Principal Symbol Theorem (GRLEPS).

The checker proves, by symbolic polynomial reduction with a *confluent
gauge-rewriting system*, that the gauge-reduced linearized vacuum Einstein
principal symbol on the spin-half clean Carter chart admits the exact
on-shell normal form

    sigma_NF == rho_backend  modulo  I_trap + <gauge-tangent SOS squares>

where:

  * sigma_NF is the normal form of the linearized Einstein principal symbol
    under the principal-trapped-gauge rewrite system R_gauge;
  * rho_backend = h*x**2 + tau*q**2 is the Kerr-clean backend density that
    QIEDT already exports;
  * I_trap = <P_R, P_dR, P_xq> is the trapped-constraint ideal, with
        P_R  = x**2 + ell**2 + q**2          (radial trapped constraint),
        P_dR = x*ell + q**2                  (radial-derivative trapped constraint),
        P_xq = x*q + ell*q - q**2            (Carter-mixed trapped constraint);
  * <gauge-tangent SOS squares> = < s*(c*x - ell)**2 >, the gauge-tangent
    SOS defect already certified by QIEDT.

The theorem closes two of the four remaining backend obligations for the
spin-half clean Carter chart:

  (1) "derive the gauge-reduced linearized vacuum Einstein principal symbol
       in this chart"
  (4) "prove the exported source density equals q_grav modulo those trapped
       constraints"

Mathematical content (the new contribution):

  (G1) Gauge-rewriting system.  R_gauge is a finite list of polynomial
       rewrite rules of the form  L_i -> R_i  with  L_i - R_i in I_trap +
       <gauge-tangent squares>.  Each rule rewrites a gauge-tangent
       monomial combination into a backend-canonical form.  The verifier
       checks, for every rule, that  L_i - R_i  lies in the augmented
       ideal  I_trap + <s*(c*x-ell)**2>, by exhibiting an explicit
       polynomial combination

           L_i - R_i = sum_j alpha_{ij} * g_j  +  beta_i * s*(c*x-ell)**2,

       where  g_j  ranges over the three trapped-constraint generators
       P_R, P_dR, P_xq.

  (G2) Confluence (critical-pair resolution).  The verifier enumerates
       every critical pair of R_gauge (a finite list of pairs of rules
       whose left-hand sides share a common sub-monomial multiple) and
       checks that each critical pair resolves, i.e. the two divergent
       one-step reductions admit a common descendant.  Local confluence
       plus termination (graded by phase degree) implies global
       confluence by Newman's lemma, hence the normal form sigma_NF is
       unique.

  (G3) Input principal-symbol structure.  The verifier checks that the
       declared input principal symbol sigma_in is a phase-homogeneous
       degree-2 polynomial in (x, ell, q) with symbolic coefficients
       drawn from {h, s, tau, c, diag_slack, bilinear_slack}, and that
       it contains at least the four mandatory gauge-tangent structures
       (the radial Hessian, the superradiant cross, the superradiant
       square, the Carter-scale diagonal).

  (G4) Reduction chain.  The verifier replays the declared finite
       reduction chain  sigma_in = s_0 -> s_1 -> ... -> s_N = sigma_NF,
       checking that each step is a single application of a rule in
       R_gauge and that  sp.expand(s_{k+1} - s_k + (L_{i_k} - R_{i_k})
       * m_k) == 0  for the declared rule  i_k  and monomial multiplier
       m_k.  This certifies that  sigma_in - sigma_NF  lies in the
       ideal generated by  L_i - R_i  for  i  in R_gauge, hence in
       I_trap + <gauge-tangent squares>.

  (G5) On-shell identity.  The verifier checks  sp.expand(sigma_NF -
       rho_backend) == 0.  Combined with (G1)+(G4), this yields
       sigma_in == rho_backend  modulo  I_trap + <gauge-tangent squares>.

  (G6) q_grav agreement.  The verifier checks that  sigma_in - q_grav
       lies in  I_trap + <gauge-tangent squares>, where  q_grav  is the
       GPDDT density.  This closes backend obligation (4): the exported
       source density (sigma_in) equals q_grav modulo the trapped
       constraints.

The verifier accepts only certificates that pass every check with exact
rational arithmetic (sympy).  It does NOT promote any candidate upstream
certificate to exact; the GRLEPS certificate must declare a
`principal_symbol_trace_certificate_path` and the verifier only checks
that the path is non-empty and free of forbidden substrings, leaving the
upstream promotion as a separate proof obligation.

Status: structural reduction, not a proof of the full conjecture.  The
GRLEPS certificate is exact conditional on the upstream principal-symbol
trace candidate being promoted from candidate to exact.  It is the
seventh primitive-packet exact-derivation theorem in the audit chain
(after RHEDT, SSEDT, CSEDT, DSEDT, BSEDT, TCDEDT, QIEDT) and the first
to address the `gauge_reduced_principal_symbol` and
`source_equals_q_grav_modulo_trapped` backend obligations.
"""

